const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const store = {};
const localStorage={ getItem:k=>store[k]||null,setItem:(k,v)=>store[k]=String(v),removeItem:k=>delete store[k] };
const context={window:{},localStorage,structuredClone,console,Date,Math,JSON}; vm.createContext(context);
for(const file of ['adaptive-engine.js','coach-engine.js']) vm.runInContext(fs.readFileSync(file,'utf8'),context);
const A=context.window.PaceAdaptive,C=context.window.PaceCoach;
A.setClock(()=>new Date(2026,10,11,10));
const settings={runSpeed:7.5,walkSpeed:5,coolSpeed:4.5};
const intake={goalType:'habit',continuousAbility:'1min',recentActivity:'walk',walkTolerance:'30',assessment:'jog',availableMinutes:30};
const plan=A.buildPlanFromIntake(intake,settings);
const base={id:'new',date:'2026-11-11',type:'Exterior',source:'timer',execution:'completed',prescriptionCompleted:true,maxRunBlockSec:60,rpe:4,pain:false,blocks:[{type:'run',actualSeconds:60,prescribedSeconds:60,runSeconds:60}]};
function decision(patch={},prior=[]){return A.decideAdaptive({...base,...patch},prior,plan);}
assert.equal(decision({rpe:9,prescriptionCompleted:false,worseningDuringRun:true}).progression,'recovery');
assert.equal(decision({rpe:9,prescriptionCompleted:false}).progression,'repeat');
for(const rpe of [7,8,9,10]) assert.equal(decision({rpe}).progression,'repeat');
for(const rpe of [null,undefined,'',NaN,11]) assert.equal(decision({rpe}).progression,'repeat');
assert.equal(decision({maxRunBlockSec:null}).progression,'repeat');
assert.equal(decision({confidence:'low'}).progression,'repeat');
assert.equal(decision().progression,'advance','first complete measured attempt at RPE 4 progresses');
assert.equal(decision({rpe:6}).progression,'repeat');
const prior=[{...base,id:'p1',date:'2026-11-09',rpe:5},{...base,id:'p2',date:'2026-11-07',rpe:5}];
assert.equal(decision({rpe:6},prior).progression,'advance');
assert.equal(decision({rpe:6},[{...prior[0],rpe:7},prior[1]]).progression,'repeat');
assert.equal(decision({rpe:6},[{...prior[0],pain:true},prior[1]]).progression,'repeat');
assert.equal(decision({rpe:6,maxRunBlockSec:30},prior).progression,'repeat','deteriorating continuous ability');
assert.equal(decision({blocks:[{prescribedSeconds:60,actualSeconds:20}],prescriptionCompleted:true}).progression,'repeat','measured blocks override self-reported completion');
const stable = A.buildPlanFromIntake({...intake,sessionsPerWeek:2},settings);
const dates = stable.sessions.map(s=>s.scheduledDate);
A.allocateScheduleDates(stable, stable.params);
assert.equal(JSON.stringify(stable.sessions.map(s=>s.scheduledDate)),JSON.stringify(dates),'opening plan does not shift all pending dates');
const scheduledRuns = stable.sessions.filter(s=>s.kind==='run');
assert.equal((new Date(scheduledRuns[1].scheduledDate)-new Date(scheduledRuns[0].scheduledDate))/86400000,3,'two days per week uses a repeating 3/4-day cadence');
const unknown=A.buildPlanFromIntake({continuousAbility:'unknown',assessment:'walk'},settings);
assert.equal(unknown.sessions[0].structure.runSeconds,0);
assert.equal(A.deriveProfile([],plan,settings).demonstratedContinuousSec,null,'declaration never becomes demonstrated ability');
assert.equal(A.metrics(plan.sessions[0].structure).totalSec,1200,'guided jog = 5 warm + 4*(1+1.5) + 5 cool');
const newbie=A.buildPlanFromIntake({continuousAbility:'none',walkTolerance:'30',assessment:'jog'},settings);
assert.equal(newbie.sessions[0].structure.runSeconds,30);
const experienced=A.buildPlanFromIntake({continuousAbility:'30min',assessment:'run',availableMinutes:45},settings);
assert.ok(experienced.sessions[0].structure.runSeconds>=1200);
assert.ok(A.metrics(A.buildPlanFromIntake({...intake,availableMinutes:15},settings).sessions[0].structure).totalSec<=900);
const painful=A.buildPlanFromIntake({...intake,hasPain:true},settings);
assert.ok(C.getFocusSession(painful).gateForId);
assert.equal(painful.sessions[0].isAssessment,false);
assert.equal(A.buildPlanFromIntake(intake,settings).raceDate,null);
let p=structuredClone(plan), logs=[];
let log={...base,planSessionId:p.sessions[0].id}; logs.push(log);
C.confirmNextSession(p,log,logs);
const count=p.sessions.flatMap(s=>s.attempts).length;
C.confirmNextSession(p,log,logs);
assert.equal(p.sessions.flatMap(s=>s.attempts).length,count,'retry never duplicates attempts or advances twice');
C.savePlan(p);C.saveLogs(logs);
const corrected=C.applyIntake({...intake,continuousAbility:'5min'},settings);
assert.equal(C.loadLogs().length,1);
assert.ok(corrected.sessions.some(s=>s.attempts.some(a=>a.logId===log.id)));
const focus=C.getFocusSession(corrected), beforeId=focus.id, beforeStructure=JSON.stringify(focus.structure);
const rescheduled=C.rescheduleFocus(corrected,'2026-11-16');
assert.equal(C.getFocusSession(rescheduled.plan).id,beforeId);
assert.equal(JSON.stringify(C.getFocusSession(rescheduled.plan).structure),beforeStructure);
// 14 actual calendar days, including complete, incomplete, hard effort, and safety recovery.
p=A.buildPlanFromIntake({...intake,assessment:'later'},settings);logs=[];const rows=[];
const outcomes={0:{rpe:4},2:{rpe:8},4:{rpe:4,prescriptionCompleted:false,execution:'aborted'},6:{rpe:4},8:{rpe:5},10:{rpe:3,worseningDuringRun:true},12:{rpe:4}};
for(let day=0;day<14;day++) {
  const date=A.addDaysISO('2026-11-11',day); A.setClock(()=>new Date(date+'T10:00:00'));
  let focus=C.getFocusSession(p); assert.ok(focus,`next action exists on day ${day}`);
  if(focus.kind==='rest') { const out=C.markRestComplete(p,logs,focus.id,date); p=out.plan;logs=out.logs;rows.push({date,result:'recovery',next:C.getFocusSession(p)?.id});continue; }
  if(!outcomes[day]){rows.push({date,result:'rest day',next:focus.id});continue;}
  const before=A.describeStructure(focus.structure);
  const actualRun=focus.structure.runSeconds*(outcomes[day].prescriptionCompleted===false?0.5:1);
  log={...base,id:'day-'+day,date,planSessionId:focus.id,maxRunBlockSec:actualRun,...outcomes[day],blocks:[{type:'run',actualSeconds:actualRun,prescribedSeconds:focus.structure.runSeconds,runSeconds:actualRun}]}; logs.push(log);
  const out=C.confirmNextSession(p,log,logs);p=out.plan;
  const nextRun=p.sessions.find(s=>s.kind==='run'&&['pending','rescheduled'].includes(s.status));
  rows.push({date,before,result:log.execution,rpe:log.rpe,decision:out.progression,next:nextRun?A.describeStructure(nextRun.structure):C.getFocusSession(p)?.title,reason:out.decision?.reason});
  if(out.progression==='repeat')assert.equal(A.describeStructure(nextRun.structure),before);
}
assert.ok(rows.some(r=>r.decision==='advance'));
assert.ok(rows.some(r=>r.decision==='repeat'));
assert.ok(rows.some(r=>r.decision==='recovery'));
assert.ok(rows.some(r=>r.before&&r.next&&r.before!==r.next&&r.decision==='advance'));
assert.ok(p.sessions.some(s=>s.kind==='run' && s.structure.runSeconds > 60), 'continuous running actually increases');
const blocked = A.buildPlanFromIntake({...intake,hasPain:true},settings);
C.rescheduleFocus(blocked,'2026-12-01');
assert.ok(C.getFocusSession(blocked).gateForId, 'rescheduling may not bypass recovery');
fs.writeFileSync('tests/requirements-14d.json',JSON.stringify(rows,null,2)+'\n');
console.log('PASS: rule priorities, RPE 6 trend, missing data, observed completion, 3 starting levels, optional assessment, availability, retained history, rescheduling, idempotency and 14 calendar days.');
